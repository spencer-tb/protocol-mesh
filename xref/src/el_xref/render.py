"""Query and render `map.json`."""

from .config import Config, Json
from .link import CONFIDENT, load_map, map_path

LINK_LIMIT = 3


def permalink(data: Json, repo: str, path: str, line: int, end: int) -> str:
    """Return a commit-pinned GitHub link to a line range."""
    info = data["repos"][repo]
    return f"{info['url']}/blob/{info['sha']}/{path}#L{line}-L{end}"


def find(data: Json, query: str) -> list[str]:
    """Return spec ids equal to, ending with, or containing `query`."""
    ids = sorted(data["entries"])
    for test in (
        lambda i: i == query,
        lambda i: i.endswith("." + query),
        lambda i: query in i,
    ):
        hits = [i for i in ids if test(i)]
        if hits:
            return hits
    return []


def show(config: Config, query: str, clients: list[str], low: bool) -> None:
    """Print where each client implements the spec functions matching."""
    data = load_map(config)
    ids = find(data, query)
    if not ids:
        print(f"no spec function matches {query!r}")
        return
    spec_repo = data["spec"]["repo"]
    for sid in ids:
        entry = data["entries"][sid]
        url = permalink(
            data, spec_repo, entry["path"], entry["line"], entry["end_line"]
        )
        print(f"{sid}\n  spec  {url}")
        for client, result in sorted(entry["clients"].items()):
            if clients and client not in clients:
                continue
            matches = [
                m
                for m in result["matches"]
                if low or m["confidence"] in CONFIDENT
            ]
            if not matches:
                hint = ", ".join(result.get("hints", [])) or "-"
                print(f"  {client:<10} no match (hints: {hint})")
                continue
            for i, m in enumerate(matches):
                label = client if i == 0 else ""
                link = permalink(
                    data, m["repo"], m["path"], m["line"], m["end_line"]
                )
                print(
                    f"  {label:<10} {m['qualname']}  "
                    f"[{m['relation']}, {m['confidence']}]\n"
                    f"  {'':<10} {link}\n"
                    f"  {'':<10} {m['note']}"
                )
        print()


def where(config: Config, query: str) -> None:
    """Print the spec functions a client function is mapped to."""
    data = load_map(config)
    lowered = query.lower()
    found = False
    for sid, entry in sorted(data["entries"].items()):
        for client, result in sorted(entry["clients"].items()):
            for m in result["matches"]:
                if lowered in m["qualname"].lower() or lowered in m["path"]:
                    found = True
                    print(
                        f"{client:<10} {m['qualname']}  ->  {sid}  "
                        f"[{m['relation']}, {m['confidence']}]"
                    )
    if not found:
        print(f"no client function matches {query!r}")


def cell(data: Json, result: Json | None) -> str:
    """Render one client column of the Markdown table."""
    if result is None:
        return ""
    matches = [m for m in result["matches"] if m["confidence"] in CONFIDENT]
    if not matches:
        return "none"
    links = []
    for m in matches[:LINK_LIMIT]:
        url = permalink(data, m["repo"], m["path"], m["line"], m["end_line"])
        mark = "" if m["relation"] == "equivalent" else " (part)"
        links.append(f"[`{m['qualname']}`]({url}){mark}")
    if len(matches) > LINK_LIMIT:
        links.append(f"+{len(matches) - LINK_LIMIT}")
    return "<br>".join(links)


def render_markdown(config: Config) -> None:
    """Write `data/MAP.md`, one table per spec module."""
    data = load_map(config)
    clients = list(config.clients)
    spec = data["spec"]
    lines = [
        f"# {spec['fork'].capitalize()} spec to client map",
        "",
        f"Spec `{spec['repo']}` at `{spec['sha'][:10]}`. Clients:",
        "",
    ]
    for name, info in sorted(data["repos"].items()):
        if name != spec["repo"]:
            lines.append(f"- `{name}` at `{info['sha'][:10]}`")
    lines += [
        "",
        "Generated by `el-xref render` from `map.json`. Links are pinned to",
        "the commits above. Only high and medium confidence matches shown.",
        "",
    ]
    modules: dict[str, list[str]] = {}
    for sid in sorted(data["entries"]):
        modules.setdefault(sid.rsplit(".", 1)[0], []).append(sid)
    used = [
        c
        for c in clients
        if any(c in e["clients"] for e in data["entries"].values())
    ]
    for module, ids in modules.items():
        lines += [
            f"## {module}",
            "",
            "| spec | " + " | ".join(used) + " |",
            "|---|" + "---|" * len(used),
        ]
        for sid in ids:
            entry = data["entries"][sid]
            url = permalink(
                data,
                spec["repo"],
                entry["path"],
                entry["line"],
                entry["end_line"],
            )
            name = sid.rsplit(".", 1)[1]
            row = [f"[`{name}`]({url})"]
            row += [cell(data, entry["clients"].get(c)) for c in used]
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")
    out = map_path(config).with_name("MAP.md")
    out.write_text("\n".join(lines))
    print(f"wrote {out}")
